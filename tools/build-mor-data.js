#!/usr/bin/env node
/* Builds ed-metrics/assets/mor-data.js from the published month pages.
   Run after adding or correcting any month:  node tools/build-mor-data.js
   Read-only on the month pages. This folder is excluded from deploys (.vercelignore). */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', 'ed-metrics');
const YEAR = 2026;
const MONTHS = [
  ['january','January','Jan','❄️'],['february','February','Feb','💝'],['march','March','Mar','🌱'],
  ['april','April','Apr','🌸'],['may','May','May','☀️'],['june','June','Jun','🏖️'],
  ['july','July','Jul','🎆'],['august','August','Aug','🌻'],['september','September','Sep','🍂'],
  ['october','October','Oct','🎃'],['november','November','Nov','🍁'],['december','December','Dec','🎄']
];
const arr = (s, name) => { const m = s.match(new RegExp('(?:const|let|var)\\s+' + name + '\\s*=\\s*(\\[[^\\]]*\\])')); return m ? Function('return ' + m[1])() : null; };
const num = (s, name) => { const m = s.match(new RegExp('(?:const|let|var|,)\\s*' + name + '\\s*=\\s*([0-9.]+)')); return m ? +m[1] : null; };
const clean = n => String(n).replace(/⭐/g, '').replace(/\s+/g, ' ').trim().toUpperCase();
const f = t => { const m = String(t).replace(/,/g, '').match(/-?[0-9]+(?:\.[0-9]+)?/); return m ? +m[0] : null; };
const hm = t => { const m = String(t).match(/(\d+)h\s*(\d+)m/); return m ? +m[1] * 60 + +m[2] : null; };

const out = { year: YEAR, all: MONTHS.map(m => [m[0], m[2], m[3]]), order: [], months: {} };
for (const [slug, label, short, emoji] of MONTHS) {
  const file = path.join(ROOT, String(YEAR), slug + '.html');
  if (!fs.existsSync(file)) continue;
  const s = fs.readFileSync(file, 'utf8');
  const k = {};
  for (const b of s.split('<div class="hkpi">').slice(1)) {
    const blk = b.split('<div class="report-body">')[0];
    const val = ((blk.match(/hkpi-val">([\s\S]*?)<\/div>/) || [])[1] || '').replace(/<[^>]+>/g, ' ').trim();
    const lab = ((blk.match(/hkpi-label">([\s\S]*?)<\/div>/) || [])[1] || '').replace(/&lt;/g, '<').trim();
    const sub = ((blk.match(/hkpi-sub">([\s\S]*?)<\/div>/) || [])[1] || '').replace(/<[^>]+>/g, ' ').trim();
    if (/Total ED Visits/i.test(lab)) { k.visits = f(val); const a = sub.match(/AVG Daily:\s*([0-9.]+)/i); if (a) k.avgDaily = +a[1]; }
    else if (/Admission Rate/i.test(lab)) k.admit = f(val);
    else if (/ESI 2 Seen/i.test(lab)) k.esi2 = f(val);
    else if (/Rapid DC/i.test(lab)) k.rapid = f(val);
    else if (/Median DC LOS/i.test(lab)) k.dcLos = hm(val);
    else if (/Door-to-Doc/i.test(lab)) k.d2d = f(val);
    else if (/LWOT Rate/i.test(lab)) k.lwot = f(val);
  }
  const prod = lab => { const m = s.match(new RegExp('prod-label">' + lab + '</div>[\\s\\S]{0,240}?<div class="prod-val"[^>]*>\\s*([0-9.,]+)')); return m ? f(m[1]) : null; };
  k.ptHr = prod('Pt / Hr'); k.apph = prod('Adjusted PPH \\(aPPH\\)');

  const pn = arr(s, 'pphNames') || [], pv = arr(s, 'pphVals') || [];
  const ln = arr(s, 'provNames') || [], lv = arr(s, 'provLOS') || [], lc = arr(s, 'provN') || [];
  if (pn.length !== pv.length) throw new Error(slug + ': pphNames/pphVals length mismatch');
  if (ln.length !== lv.length || ln.length !== lc.length) throw new Error(slug + ': provNames/provLOS/provN length mismatch');
  const pph = {}, los = {};
  pn.forEach((n, i) => { pph[clean(n)] = pv[i]; });
  ln.forEach((n, i) => { los[clean(n)] = [lv[i], lc[i]]; });
  out.order.push(slug);
  out.months[slug] = {
    label, short, emoji,
    deptPph: num(s, 'DEPT_AVG'), pphStar: num(s, 'PPH_STAR') || 1.88, losStar: num(s, 'LOS_STAR') || 200,
    losStat: /Mean Discharge LOS by Provider/.test(s) ? 'mean' : 'median',
    kpi: k, pph, los
  };
}
const body = '/* GENERATED by tools/build-mor-data.js — do not edit by hand. */\nwindow.MOR_DATA=' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(ROOT, 'assets', 'mor-data.js'), body);
console.log('mor-data.js written:', out.order.length, 'months,', body.length, 'bytes');
for (const m of out.order) { const d = out.months[m]; console.log(' ', m.padEnd(10), 'pph', Object.keys(d.pph).length, 'los', Object.keys(d.los).length, d.losStat, JSON.stringify(d.kpi)); }
